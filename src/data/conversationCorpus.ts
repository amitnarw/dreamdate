function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function capitalize(s: string): string {
  if (!s) return s;
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/* ---------------- slot composition ---------------- */

export interface ComposeOptions {
  /** Probability of prepending an opener (default 0.5). */
  openerProb?: number;
  /** Probability of inserting a mid-clause (default 0.3). */
  midProb?: number;
  /** Probability of appending a closer particle (default 0.4). */
  closerProb?: number;
  /** Probability of trailing emoji (default 0.55). */
  trailProb?: number;
}

const DEFAULT_OPTS: Required<ComposeOptions> = {
  openerProb: 0.5,
  midProb: 0.3,
  closerProb: 0.4,
  trailProb: 0.55,
};

function insertParticle(
  base: string,
  particle: string,
): string {
  if (!particle) return base;
  const m = base.match(/^([\s\S]{0,12}\s)([\s\S]+)$/);
  if (!m) return base + " " + particle;
  return m[1] + particle + " " + m[2].trimStart();
}

export function composeBase(
  base: string,
  arch: CharacterArchetype,
  opts?: ComposeOptions,
): string {
  const o = { ...DEFAULT_OPTS, ...(opts || {}) };
  let out = base.trim();
  if (Math.random() < o.midProb) {
    out = insertParticle(out, pick(MIDS[arch]).trim());
  }
  if (Math.random() < o.openerProb) {
    out = (pick(OPENERS[arch]).trim() + " " + out).trim();
  }
  if (Math.random() < o.closerProb) {
    out = out + pick(CLOSERS[arch]);
  }
  if (Math.random() < o.trailProb) {
    out = out + pick(TRAIL_EMOJI[arch]);
  }
  out = out.replace(/\s+/g, " ").trim();
  out = capitalize(out);
  return out;
}

export function getPool(intent: CorpusIntent, arch: CharacterArchetype): string[] {
  return POOLS[intent][arch] || POOLS[intent].playful_tease;
}
